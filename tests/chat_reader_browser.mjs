#!/usr/bin/env node
// Only the opt-in Go fixture supplies this isolated server and fake ACP agent.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const { chromium } = createRequire(fileURLToPath(new URL('../ui/package.json', import.meta.url)))('playwright');
const origin = process.env.POCKETCONTEXT_SYNTHETIC_CHAT_ORIGIN;
assert(/^http:\/\/127\.0\.0\.1:\d+$/.test(origin || ''));
const signIn = process.env.POCKETCONTEXT_SYNTHETIC_SIGNIN;
assert(signIn?.startsWith(`${origin}/bundle/login#`));
const browser = await chromium.launch({args:['--no-proxy-server']});
const problems=[];
try {
 const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 await context.route('**/*',async route=>{
  if(!route.request().url().startsWith(`${origin}/`)){problems.push('unexpected external request');await route.abort();}
  else await route.continue();
 });
 const page=await context.newPage();
 page.on('pageerror',error=>problems.push(error.message));
 await page.addInitScript(() => {
   window.SpeechRecognition = class {
     start(){this.onresult({resultIndex:0,results:[{isFinal:true,0:{transcript:"hello"}}]});queueMicrotask(()=>this.onend());}
     stop(){} abort(){}
   };
 });
 await page.goto(signIn);
 await page.waitForURL(`${origin}/`);
 const destinations=page.getByRole('navigation',{name:'Workspace navigation'});
 await page.getByRole('button',{name:'Back to spaces'}).click();
 const spaceList=page.getByRole('region',{name:'Spaces list'});
 await spaceList.getByRole('button',{name:'Research notebook'}).click();
 assert.equal(await destinations.isVisible(),false);
 await page.getByRole('button',{name:'Back to spaces'}).click();
 await destinations.getByRole('button',{name:'New space'}).click();
 await spaceList.getByLabel('Space name').fill('Mobile test space');
 await spaceList.getByRole('button',{name:'Create space'}).click();
 await spaceList.waitFor({state:'hidden'});
 await page.getByRole('button',{name:'Back to spaces'}).click();
 await spaceList.getByRole('button',{name:'Mobile test space'}).waitFor();
 await spaceList.getByRole('button',{name:'Default'}).click();
 await page.getByRole('button',{name:'Back to spaces'}).click();
 await page.getByRole('button',{name:'Chats',exact:true}).click();
 const dialog=page.getByRole('region',{name:'Chat workspace'});
 await destinations.getByRole('button',{name:'New chat'}).click();
 await page.getByRole('dialog',{name:'Choose a space for this chat'}).getByRole('button',{name:'Research notebook'}).click();
 const shield=dialog.getByRole('button',{name:'Chat permissions',exact:true});
 await shield.click();
 await dialog.getByRole('radio',{name:/Read-only/}).waitFor();
 await page.keyboard.press('Escape');
 await dialog.getByRole('radio',{name:/Read-only/}).waitFor({state:'hidden'});
 const send=dialog.getByRole('button',{name:'Send',exact:true});
 await dialog.getByLabel('Model',{exact:true}).selectOption('second');
 await dialog.locator('input[type=file]').setInputFiles({name:'pixel.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a2ZkAAAAASUVORK5CYII=','base64')});
 await dialog.getByRole('img',{name:'Attachment 1',exact:true}).waitFor();
 await dialog.getByRole('button',{name:'Dictate message'}).click();
 assert.equal(await dialog.getByLabel('Message',{exact:true}).inputValue(),'hello');
 await send.click();
 await dialog.getByRole('article',{name:'Agent reply'}).getByText('Synthetic response',{exact:true}).waitFor();
 await dialog.getByRole('img',{name:'Attached image 1',exact:true}).waitFor();
 assert.equal(await dialog.getByLabel('Model',{exact:true}).inputValue(),'second');
 await dialog.getByText(/^Worked for /).waitFor();
 const history=dialog.getByRole('navigation',{name:'Chat history'});
 const spaceHeader=dialog.getByLabel('Conversation space');
 assert.equal(await spaceHeader.isVisible(),true);
 const scroller=dialog.locator('.chat-thread-scroll');
 const longReply=await scroller.evaluateHandle(el=>{const reply=document.createElement('p');reply.textContent='A long response. '.repeat(700);el.querySelector('.chat-thread-content').append(reply);return reply;});
 const beforeScroll=await spaceHeader.boundingBox();
 const atBottom=()=>page.waitForFunction(()=>{const el=document.querySelector('.chat-thread-scroll');return el.scrollTop>0 && el.scrollHeight-el.clientHeight-el.scrollTop<2});
 await atBottom();
 assert(await scroller.evaluate(el=>el.scrollTop>0));
 assert.equal((await spaceHeader.boundingBox()).y,beforeScroll.y,'header stays fixed above long replies');
 assert((await scroller.boundingBox()).y>=beforeScroll.y+beforeScroll.height-1,'messages scroll below the header');
 await scroller.evaluate(el=>{el.scrollTop=0});
 const historyToggle=page.getByRole('button',{name:'Back to chats'});
 await page.waitForFunction(()=>{const pager=document.querySelector('.chat-layout');return Math.abs(pager.scrollLeft-pager.clientWidth)<=2 && pager.querySelector('.chat-history').inert});
 assert.equal(await destinations.isVisible(),false);
 await historyToggle.click();
 assert.equal(await destinations.isVisible(),true);
 await history.getByRole('button',{name:'hello',exact:true}).first().click();
 await page.waitForFunction(()=>{const pager=document.querySelector('.chat-layout');return Math.abs(pager.scrollLeft-pager.clientWidth)<=2 && pager.querySelector('.chat-history').inert});
 await atBottom();
 await longReply.evaluate(el=>el.remove());
 await page.setViewportSize({width:1280,height:800});
 await page.waitForFunction(()=>{const pager=document.querySelector('.chat-layout');return Math.abs(pager.scrollLeft-pager.clientWidth)<=2 && pager.querySelector('.chat-history').inert});
 assert.equal(await spaceHeader.isVisible(),true);
 await page.waitForFunction(()=>{const pager=document.querySelector('.chat-layout');return pager.scrollLeft>=pager.clientWidth-2});
 await page.setViewportSize({width:390,height:844});
 await dialog.getByLabel('Message',{exact:true}).fill('permission');
 await send.click();
 await dialog.getByRole('heading',{name:'Approval requested'}).waitFor();
 assert.equal(await destinations.isVisible(),false);
 await historyToggle.click();
 assert.equal(await destinations.isVisible(),true);
 await history.getByText('Approval needed',{exact:true}).waitFor();
 await destinations.getByRole('button',{name:'Spaces',exact:true}).click();
 await page.reload();
 await page.getByRole('button',{name:'Back to spaces'}).click();
 await page.getByRole('button',{name:'Chats',exact:true}).click();
 await dialog.getByRole('button',{name:'hello',exact:true}).first().click();
 await dialog.getByRole('heading',{name:'Approval requested'}).waitFor();
 const reject=dialog.getByRole('button',{name:/reject/i});
 await reject.click();
 await dialog.getByRole('heading',{name:'Approval requested'}).waitFor({state:'hidden'});
 await page.setViewportSize({width:390,height:480});
 await dialog.getByLabel('Message',{exact:true}).fill('hang');
 const field=await dialog.getByLabel('Message',{exact:true}).boundingBox();
 assert(field && field.y>=0 && field.y+field.height<=480,'composer fits a shortened phone viewport');
 await send.click();
 await dialog.getByRole('button',{name:'Stop',exact:true}).waitFor();
 await dialog.getByLabel('Conversation messages').getByRole('timer',{name:'Agent working'}).waitFor();
 assert.equal(await spaceHeader.getByRole('timer').count(),0);
 await dialog.getByText(/^Working for \d+s$/).waitFor();
 assert.equal(await send.count(),0);
 await dialog.getByRole('button',{name:'Stop',exact:true}).click();
 await dialog.getByRole('button',{name:'Stop',exact:true}).waitFor({state:'hidden'});
 await send.waitFor();
 await dialog.getByRole('timer',{name:'Agent working'}).waitFor({state:'hidden'});
 assert.equal(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth),true,'phone drawer fits viewport');
 assert.deepEqual(problems,[]);
 console.log('ok - phone chat, streaming, native permission rejection, reload reconnect, cancellation, end conversation');
 await context.close();
} finally {await browser.close();}
