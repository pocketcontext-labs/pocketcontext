import { readFile } from "node:fs/promises";
import { expect, test } from "@playwright/test";

test("audio catalog: protected playback, bundle previews, historical selection and session cleanup", async ({page, request}) => {
  test.setTimeout(90_000);
  const seed = await request.post(process.env.WIKICONTEXT_TEST_CONTROL + "/audio");
  expect(seed.ok(), await seed.text()).toBeTruthy();
  const fixture = await seed.json();
  await page.goto("/#/catalog/audio_recording");
  await page.getByText("Sign in with a password", {exact:true}).click();
  await page.getByLabel("Email", {exact:true}).fill("agent@example.com");
  await page.getByLabel("Password", {exact:true}).fill("SyntheticUserPassword123!");
  await page.getByRole("button", {name:"Sign in",exact:true}).click();
  const catalog = page.getByRole("region", {name:"Audio catalog"});
  await expect(catalog.getByRole("status")).toHaveText("2 recordings");
  await page.getByLabel("Bundle availability").selectOption("selected");
  await expect(catalog.getByRole("status")).toHaveText("1 recordings");
  await page.getByLabel("Language").selectOption("English");
  await page.reload();
  await expect(page.getByLabel("Language")).toHaveValue("English");
  await catalog.getByRole("link", {name:"Synthetic recording",exact:true}).click();
  const recording = page.getByRole("region", {name:"Audio recording"});
  await expect(recording.getByLabel("Extraction version")).toHaveValue(fixture.first);
  await expect(recording).toContainText("Timestamps are approximate");
  await recording.getByRole("button", {name:"Transcript",exact:true}).focus();
  await page.keyboard.press("Enter");
  await expect(recording).toContainText("Alice (SPEAKER_01): Synthetic evidence.");
  await expect(recording.getByRole("link", {name:/segment seg000001/})).toHaveAttribute("href", /passages\//);
  await recording.getByRole("button", {name:"Analysis",exact:true}).click();
  await expect(recording.locator(".audio-analysis")).toContainText("The synthetic team agreed to review the report.");
  await recording.getByRole("button", {name:"Translation",exact:true}).click();
  await expect(recording.locator(".audio-analysis")).toContainText("Prova sintetica.");
  await expect(recording.locator(".audio-analysis")).toContainText("Alice (SPEAKER_01)");
  await recording.getByRole("button", {name:"Files and provenance",exact:true}).click();
  await expect(recording.getByRole("button", {name:"Download Analysis",exact:true})).toBeVisible();
  await expect(recording.getByRole("region", {name:"Generation provenance"})).toContainText("Pipeline and usage: Unavailable");
  const downloadEvent = page.waitForEvent("download");
  await recording.getByRole("button", {name:"Download Analysis",exact:true}).click();
  const download = await downloadEvent;
  expect(JSON.parse((await readFile((await download.path())!)).toString()).summary[0].text).toBe("The synthetic team agreed to review the report.");
  await page.route("**/api/files/sources/**", route => route.fulfill({status:403,body:"Unavailable"}));
  await recording.getByRole("button", {name:"Analysis",exact:true}).click();
  await expect(recording.getByRole("status")).toContainText("Unable to load protected recording evidence");
  await expect(recording.locator(".audio-analysis")).toHaveCount(0);
  await page.unroute("**/api/files/sources/**");
  await recording.getByRole("button", {name:"Load audio",exact:true}).click();
  const player = recording.locator("audio");
  await expect(player).toHaveAttribute("src", /^blob:/);
  await player.evaluate(async (node: HTMLAudioElement) => {node.muted=true; await node.play();});
  await expect.poll(()=>player.evaluate((node: HTMLAudioElement)=>node.readyState)).toBeGreaterThanOrEqual(2);
  expect(await player.evaluate((node: HTMLAudioElement)=>node.duration)).toBeCloseTo(1,1);
  await recording.getByLabel("Extraction version").selectOption(fixture.second);
  await recording.getByRole("button", {name:"Transcript",exact:true}).click();
  await expect(recording).toContainText("Reviewed Alice (SPEAKER_01): Synthetic evidence.");
  await recording.getByRole("button", {name:"Files and provenance",exact:true}).click();
  await expect(recording.getByRole("region", {name:"Generation provenance"})).toContainText("Long decode (continuation enabled)");
  await expect(recording.getByRole("region", {name:"Generation provenance"})).toContainText("Continuation responses: 1");
  await expect(recording.getByRole("region", {name:"Generation provenance"})).toContainText("200");
  await recording.getByLabel("Extraction version").selectOption(fixture.first);
  await expect(recording.getByRole("region", {name:"Generation provenance"})).toHaveCount(0);
  await recording.getByRole("button", {name:"Files and provenance",exact:true}).click();
  await expect(recording.getByRole("region", {name:"Generation provenance"})).toContainText("Pipeline and usage: Unavailable");
  await page.reload();
  await expect(recording.getByLabel("Extraction version")).toHaveValue(fixture.first);
  const update = await request.post(process.env.WIKICONTEXT_TEST_CONTROL + "/audio-update");
  expect(update.ok(), await update.text()).toBeTruthy();
  await expect(recording.getByLabel("Extraction version")).toHaveValue(fixture.second);
  await page.goto(`/#/page/synthetic-recording?publication=${fixture.publication}`);
  await expect(recording.getByLabel("Extraction version")).toHaveValue(fixture.first);
  await page.setViewportSize({width:390,height:844});
  await recording.getByRole("button", {name:"Analysis",exact:true}).click();
  await expect(recording.locator(".audio-analysis")).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({path:"/tmp/wikicontext-audio-mobile.png",fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:"/tmp/wikicontext-audio-desktop.png",fullPage:true});
  await recording.getByRole("button", {name:"Load audio",exact:true}).click();
  await expect(player).toHaveAttribute("src",/^blob:/);
  try {
    const revoke = await request.post(process.env.WIKICONTEXT_TEST_CONTROL + "/revoke-company");
    expect(revoke.ok(), await revoke.text()).toBeTruthy();
    await page.evaluate(()=>window.dispatchEvent(new Event("focus")));
    await expect(page.locator("audio")).toHaveCount(0);
    await expect(page.getByText("The synthetic team agreed to review the report.", {exact:true})).toHaveCount(0);
  } finally {
    const restore = await request.post(process.env.WIKICONTEXT_TEST_CONTROL + "/restore-company");
    expect(restore.ok(), await restore.text()).toBeTruthy();
  }
  await page.reload();
  await recording.getByRole("button", {name:"Load audio",exact:true}).click();
  await expect(player).toHaveAttribute("src",/^blob:/);
  await page.getByRole("button", {name:"Sign out",exact:true}).click();
  await expect(page.locator("audio")).toHaveCount(0);
  await expect(page.getByText("The synthetic team agreed to review the report.", {exact:true})).toHaveCount(0);
});
